import { createClient } from '@supabase/supabase-js'

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL || ''
const supabaseAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY || ''

// Check if credentials are validly supplied (not empty and not default placeholder)
export const isSupabaseConfigured = Boolean(
  supabaseUrl && 
  supabaseAnonKey && 
  !supabaseUrl.includes('your-project-id') &&
  !supabaseAnonKey.includes('your-supabase-anon-key')
)

// Fallback to a valid format URL if unconfigured to avoid initialization exception
const safeUrl = isSupabaseConfigured ? supabaseUrl : 'https://placeholder-project.supabase.co'
const safeKey = isSupabaseConfigured ? supabaseAnonKey : 'dummy-anon-key'

export const supabase = createClient(safeUrl, safeKey, {
  auth: {
    persistSession: true,
    autoRefreshToken: true,
    detectSessionInUrl: true,
  },
})
